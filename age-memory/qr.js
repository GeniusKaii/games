/**
 * 在 canvas 上画二维码
 * @param {CanvasRenderingContext2D} ctx
 * @param {number} x 左上角 x
 * @param {number} y 左上角 y
 * @param {number} size 边长（含静区）
 * @param {string} dark 深色（默认近黑）
 * @param {string} light 浅色（默认白）
 */
export function drawQR(ctx, x, y, size, dark = '#16101f', light = '#ffffff') {
  const n = QR_PATTERN.length;
  const quiet = 4;                    // 静区模块数，微信识别需要
  const total = n + quiet * 2;
  const cell = size / total;

  // 白色底（含静区）
  ctx.fillStyle = light;
  ctx.fillRect(x, y, size, size);

  ctx.fillStyle = dark;
  const ox = x + quiet * cell;
  const oy = y + quiet * cell;

  for (let r = 0; r < n; r++) {
    const row = QR_PATTERN[r];
    for (let c = 0; c < n; c++) {
      if (row[c] === '1') {
        // 用 round 让相邻像素无缝
        const px = Math.round(ox + c * cell);
        const py = Math.round(oy + r * cell);
        const px2 = Math.round(ox + (c + 1) * cell);
        const py2 = Math.round(oy + (r + 1) * cell);
        ctx.fillRect(px, py, px2 - px, py2 - py);
      }
    }
  }
}

